/**
 * Search the table.
 *
 * Matches the character itself as well as its terms, so pasting an emoji into
 * the box finds it — which is how somebody asks "what is this one called".
 * An empty query returns nothing rather than everything: the caller shows its
 * groups in that case, and returning 300 results for no input would replace a
 * browsable picker with a wall.
 */
export function searchEmoji(query: string, limit = 60): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (q.length === 0) return [];
  const all = EMOJI_GROUPS.flatMap((g) => g.emoji);

  // Terms that START with the query rank above ones that merely contain it, so
  // "car" offers 🚗 before 🃏-adjacent matches like "card".
  const starts: EmojiEntry[] = [];
  const contains: EmojiEntry[] = [];
  for (const entry of all) {
    if (entry[0] === q) {
      starts.push(entry);
      continue;
    }
    const terms = entry[1].split(" ");
    if (terms.some((t) => t.startsWith(q))) starts.push(entry);
    else if (entry[1].includes(q)) contains.push(entry);
  }
  return [...starts, ...contains].slice(0, limit);
}
