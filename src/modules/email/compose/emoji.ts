/**
 * The emoji the picker offers.
 *
 * WHY THIS IS A HAND-WRITTEN TABLE RATHER THAN A DEPENDENCY. The full Unicode
 * emoji set is ~1,900 characters and the libraries that ship it carry a
 * megabyte of data plus a picker component with its own opinions. This is a
 * business mail composer: the useful set is the couple of hundred that appear in
 * work correspondence, and shipping the other seventeen hundred costs every
 * reader of every page a download for skin-tone variants of a mermaid.
 *
 * WHY IT NEEDS NO SANITIZER RULE AT ALL, which is the reason emoji were the
 * cheapest thing on the list: **an emoji is a text character, not an image.**
 * It is inserted with `insertText`, travels in the HTML part as a UTF-8
 * character, and survives into the plain-text alternative for free. Nothing in
 * `compose/html.ts` had to change. The `<img>`-based emoji some clients use
 * would have needed the opposite of everything that file is built around.
 *
 * Pure, free of `server-only`.
 */

export interface EmojiGroup {
  id: string;
  label: string;
  /** Shown on the category tab. Itself an emoji, so no icon import. */
  icon: string;
  emoji: readonly EmojiEntry[];
}

